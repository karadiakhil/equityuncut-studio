// Bundle the engine into dist/studio.js (+ vendor scripts, fonts, textures) and sync it into HyperFrames projects.
//   node build.mjs            -> dist/
//   node build.mjs --sync     -> also copies dist + fonts + textures into previews/qa03/assets/
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const P = (...a) => path.join(here, ...a);
const ORDER = ['lib/core.js', 'lib/asset-normalizer.js', 'library/props/icons.generated.js', 'library/textures/textures.js',
  'library/props/props.js', 'library/props/libsvg.js', 'library/mograph/mograph.js', 'library/mograph/kit.js', 'cast/hand-poses.js', 'cast/lipsync.js', 'cast/CharacterRig.js',
  'cast/characters.js', 'cast/characters2.js', 'cast/paper8.js', 'actions/choreography.js', 'actions/acting.js', 'world/StageEngine.js', 'world/CameraRig.js',
  'world/Lighting.js', 'world/Brand.js', 'world/WorldKit.js', 'world/SetLibrary.js', 'world/SceneSpec.js'];
// icon subset (fluent-emoji-flat, MIT) -> library/props/icons.generated.js
const ICONS = ['potted-plant', 'luggage', 'airplane', 'small-airplane', 'money-bag', 'laptop', 'briefcase', 'globe-showing-americas',
  'telephone', 'office-building', 'cityscape', 'ledger', 'mobile-phone', 'dollar-banknote', 'newspaper', 'classical-building', 'bank',
  'chart-increasing', 'books', 'herb', 'key', 'locked', 'mantelpiece-clock', 'hot-beverage', 'card-index-dividers'];
const set = JSON.parse(fs.readFileSync(P('node_modules/@iconify-json/fluent-emoji-flat/icons.json'), 'utf8'));
const sub = {}; for (const k of ICONS) if (set.icons[k]) sub[k] = set.icons[k].body;
fs.mkdirSync(P('library/props'), {recursive: true});
fs.writeFileSync(P('library/props/icons.generated.js'), `/* generated by build.mjs from @iconify-json/fluent-emoji-flat (MIT, Microsoft Fluent Emoji). Do not edit. */\n(function (S) { S.ICONS = ${JSON.stringify({w: set.width || 32, h: set.height || 32, icons: sub})}; })(window.Studio = window.Studio || {});\n`);
let out = `/* Equity Uncut studio engine bundle. Built ${'by build.mjs'} from shared-studio sources. */\n`;
for (const f of ORDER) { if (!fs.existsSync(P(f))) { console.warn('skip (missing):', f); continue; } out += `\n/* ---- ${f} ---- */\n` + fs.readFileSync(P(f), 'utf8'); }
fs.mkdirSync(P('dist/vendor'), {recursive: true});
fs.writeFileSync(P('dist/studio.js'), out);
fs.copyFileSync(P('node_modules/gsap/dist/gsap.min.js'), P('dist/vendor/gsap.min.js'));
// rough.js falls back to Math.random() only when no seed is given; we always seed, and swap the fallback for a fixed LCG
// so the bundle is deterministic by construction (HyperFrames lint: non_deterministic_code).
fs.writeFileSync(P('dist/vendor/rough.js'), fs.readFileSync(P('node_modules/roughjs/bundled/rough.js'), 'utf8')
  .replace(/Math\.random\(\)/g, '((globalThis.__roughLcg = ((globalThis.__roughLcg || 1) * 16807) % 2147483647) / 2147483647)'));
// fonts
const FONTS = [['archivo-black', 'archivo-black-latin-400-normal.woff2'], ['plus-jakarta-sans', 'plus-jakarta-sans-latin-800-normal.woff2'],
  ['plus-jakarta-sans', 'plus-jakarta-sans-latin-600-normal.woff2'], ['inter', 'inter-latin-400-normal.woff2'], ['inter', 'inter-latin-700-normal.woff2'],
  ['jetbrains-mono', 'jetbrains-mono-latin-700-normal.woff2'], ['jetbrains-mono', 'jetbrains-mono-latin-400-normal.woff2']];
fs.mkdirSync(P('dist/fonts'), {recursive: true});
for (const [pkg, file] of FONTS) fs.copyFileSync(P('node_modules/@fontsource', pkg, 'files', file), P('dist/fonts', file));
fs.copyFileSync(P('lib/fonts.css'), P('dist/fonts.css'));
console.log('dist/studio.js', (out.length / 1024).toFixed(1) + ' KB');
if (process.argv.includes('--sync')) {
  for (const proj of ['previews/qa03', '../episodes/ep02-nk-remote-workers/skit-ch01', '../episodes/ep02-nk-remote-workers/film']) {
    if (!fs.existsSync(P(proj))) continue;
    const A = P(proj, 'assets'); fs.mkdirSync(A, {recursive: true});
    fs.cpSync(P('dist'), A, {recursive: true});
    if (fs.existsSync(P('library/textures/baked'))) fs.cpSync(P('library/textures/baked'), path.join(A, 'textures'), {recursive: true});
    console.log('synced ->', proj);
  }
}
